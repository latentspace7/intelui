import argparse
import json
from pathlib import Path

import httpx

QUESTIONS = [
    "What is the total revenue across all bookings?",
    "Show revenue by Economy, Premium Economy, Business, and First Class.",
    "Which routes generated the highest revenue?",
    "What percentage of flights were cancelled?",
    "How have cancellations changed over the last six months?",
    "Which customers have submitted the most complaints?",
    "What are the most common complaint categories?",
    "Show unresolved complaints associated with business-class passengers.",
    "Which flights generated the most customer support requests?",
    "Compare revenue generated by loyal customers versus occasional travelers.",
    "Show the average ticket price by travel class.",
    "Which customers experienced a cancelled flight and subsequently contacted customer support?",
    "Summarize customer complaints related to delayed flights.",
    "What percentage of refund requests remain unresolved?",
    "Generate an executive summary of the airline's operational performance.",
]


def main():
    parser = argparse.ArgumentParser(
        description="Runs real, billable model requests through the API."
    )
    parser.add_argument("--base-url", default="http://127.0.0.1:8000")
    parser.add_argument("--output", default="/tmp/aerovista-live-results.json")
    parser.add_argument("--only", type=int, nargs="*")
    args = parser.parse_args()
    results = []
    with httpx.Client(base_url=args.base_url, timeout=360) as client:
        for number, question in enumerate(QUESTIONS, 1):
            if args.only and number not in args.only:
                continue
            response = client.post("/api/analyses", json={"question": question})
            row = {"scenario": number, "question": question, "status": response.status_code}
            body = response.json()
            if response.is_success:
                snapshot = body["snapshot"]
                row.update(
                    id=body["id"],
                    row_count=snapshot["result"]["row_count"],
                    sections=[s["kind"] for s in snapshot["presentation"]["sections"]]
                    if snapshot["presentation"]
                    else [],
                    sql=snapshot["result"]["sql"],
                    rows=snapshot["result"]["rows"],
                    summary=snapshot["summary"],
                )
            else:
                row["error"] = body
            results.append(row)
            Path(args.output).write_text(json.dumps(results, indent=2))
            print(
                json.dumps({k: v for k, v in row.items() if k not in ("sql", "rows", "summary")}),
                flush=True,
            )
    raise SystemExit(0 if all(r["status"] == 201 and r["row_count"] > 0 for r in results) else 1)


if __name__ == "__main__":
    main()
